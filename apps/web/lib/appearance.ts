/**
 * Appearance, the reader's choice (D-196): the app's colour, the contrast level
 * and motion. The theme (light/dark) lives in `lib/theme.ts` and the table
 * density in `lib/density.ts`; the Aparência page shows all of them together.
 *
 * Kept on this device, in `localStorage`, the way the theme and the density are.
 * Every access is in try/catch: private mode or a full disk only means the choice
 * is not remembered.
 *
 * Nothing here invents a colour. "A cor do app" picks one of the route palettes
 * already in `app/globals.css` — ramps built by the OKLCH recipe of D-38/D-73,
 * contrast-checked by `scripts/design/verify-globals-contrast.py`, with their M3
 * roles generated by `npm run tokens:m3` — and wears it on every screen. The
 * quality colours and the Okabe–Ito chart palette never move (D-181).
 */

export type AppColor = "route" | "azul" | "verde-azulado" | "verde" | "violeta" | "rosa" | "terracota";
export type ContrastLevel = "standard" | "medium" | "high";
export type MotionPreference = "standard" | "reduced";
/** D-236: the rail is dark by default (D-37, D-181); "light" is an option, in the light theme only. */
export type RailPreference = "dark" | "light";

export interface Appearance {
  color: AppColor;
  contrast: ContrastLevel;
  motion: MotionPreference;
  rail: RailPreference;
}

export const DEFAULT_APPEARANCE: Appearance = { color: "route", contrast: "standard", motion: "standard", rail: "dark" };

/**
 * The palette each colour wears: the `[data-section]` whose block already holds
 * it, light and dark. Blue is Processos (hue 250) rather than the default of
 * `:root` (262): "inicio" has no block of its own, so a swatch under it would
 * inherit whatever colour the page wears instead of showing blue.
 */
export const APP_COLOR_SECTION: Record<Exclude<AppColor, "route">, string> = {
  azul: "processos",
  "verde-azulado": "mapas",
  verde: "importar",
  violeta: "selecao",
  rosa: "comparar",
  terracota: "painel",
};

export const APP_COLORS = ["route", ...Object.keys(APP_COLOR_SECTION)] as AppColor[];
const CONTRASTS: ContrastLevel[] = ["standard", "medium", "high"];
const MOTIONS: MotionPreference[] = ["standard", "reduced"];
const RAILS: RailPreference[] = ["dark", "light"];

export const APPEARANCE_STORAGE_KEY = "msai.appearance";

function isOneOf<T extends string>(value: unknown, options: readonly T[]): value is T {
  return typeof value === "string" && (options as readonly string[]).includes(value);
}

/** Whatever was stored, as a valid appearance; anything unknown falls back to the default. */
export function parseAppearance(raw: string | null): Appearance {
  if (!raw) return DEFAULT_APPEARANCE;
  try {
    const data = JSON.parse(raw) as Record<string, unknown>;
    return {
      color: isOneOf(data.color, APP_COLORS) ? data.color : DEFAULT_APPEARANCE.color,
      contrast: isOneOf(data.contrast, CONTRASTS) ? data.contrast : DEFAULT_APPEARANCE.contrast,
      motion: isOneOf(data.motion, MOTIONS) ? data.motion : DEFAULT_APPEARANCE.motion,
      rail: isOneOf(data.rail, RAILS) ? data.rail : DEFAULT_APPEARANCE.rail,
    };
  } catch {
    return DEFAULT_APPEARANCE;
  }
}

/** The palette to wear: the route's own, unless the reader chose one for the whole app. */
export function paletteSection(color: AppColor, routeSection: string): string {
  return color === "route" ? routeSection : APP_COLOR_SECTION[color];
}

/**
 * Runs before first paint, inlined in the document head next to the theme's.
 * Same reason, same shape: a contrast or a colour applied after paint is a
 * flash. "standard" leaves the attribute off, so the CSS can still follow the
 * system's "increase contrast" and "reduce motion" (see globals.css).
 */
export const APPEARANCE_BOOTSTRAP_SCRIPT = `!function(){try{var a=JSON.parse(localStorage.getItem(${JSON.stringify(
  APPEARANCE_STORAGE_KEY,
)})||"{}"),r=document.documentElement,s=${JSON.stringify(
  APP_COLOR_SECTION,
)};if(a.contrast==="medium"||a.contrast==="high")r.dataset.contrast=a.contrast;if(a.motion==="reduced")r.dataset.motion="reduced";if(a.rail==="light")r.dataset.rail="light";if(s[a.color])r.dataset.section=s[a.color]}catch(e){}}()`;

/** Writes the contrast and motion attributes; the colour goes through `SectionTheme`. */
export function applyAppearanceToDocument(appearance: Appearance, root: HTMLElement): void {
  if (appearance.contrast === "standard") delete root.dataset.contrast;
  else root.dataset.contrast = appearance.contrast;
  if (appearance.motion === "reduced") root.dataset.motion = "reduced";
  else delete root.dataset.motion;
  if (appearance.rail === "light") root.dataset.rail = "light";
  else delete root.dataset.rail;
}

// --- The store, in the shape `useSyncExternalStore` wants (as lib/theme.ts). ---

const listeners = new Set<() => void>();
let cachedRaw: string | null | undefined;
let cached: Appearance = DEFAULT_APPEARANCE;

function readRaw(): string | null {
  try {
    return window.localStorage.getItem(APPEARANCE_STORAGE_KEY);
  } catch {
    return null;
  }
}

/** The stored appearance; the same object while nothing changed, as the hook requires. */
export function readAppearance(): Appearance {
  if (typeof window === "undefined") return DEFAULT_APPEARANCE;
  const raw = readRaw();
  if (raw !== cachedRaw) {
    cachedRaw = raw;
    cached = parseAppearance(raw);
  }
  return cached;
}

export function serverAppearance(): Appearance {
  return DEFAULT_APPEARANCE;
}

export function subscribeAppearance(onChange: () => void): () => void {
  listeners.add(onChange);
  const onStorage = (event: StorageEvent) => {
    if (event.key === null || event.key === APPEARANCE_STORAGE_KEY) {
      applyAppearanceToDocument(readAppearance(), document.documentElement);
      onChange();
    }
  };
  window.addEventListener("storage", onStorage);
  return () => {
    listeners.delete(onChange);
    window.removeEventListener("storage", onStorage);
  };
}

/** Changes part of the appearance, applies it now and remembers it. */
export function setAppearance(change: Partial<Appearance>): Appearance {
  const next = { ...readAppearance(), ...change };
  applyAppearanceToDocument(next, document.documentElement);
  try {
    window.localStorage.setItem(APPEARANCE_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // Not remembered; this page still wears it.
  }
  cachedRaw = undefined;
  for (const listener of listeners) listener();
  return next;
}

/**
 * Whether motion is off: the reader's choice here, or the system's. The one
 * question every script that animates asks (CSS answers it in globals.css).
 */
export function prefersReducedMotion(): boolean {
  if (typeof window === "undefined") return false;
  if (document.documentElement.dataset.motion === "reduced") return true;
  return typeof window.matchMedia === "function" && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}
