/**
 * Material 3 color roles, derived per route (D-133).
 *
 * `materialTheme.ts` builds the `--md-sys-color-*` scheme from one blue seed;
 * this module builds the same family from each route's own `--accent`, so a
 * route keeps its hue (D-38/D-73) and still gets the full M3 pairing: every
 * fill has its `on-…`, plus the five surface containers, outline and the
 * inverse trio. Output is "R G B" triples, the form every other token in
 * `app/globals.css` takes (the Tailwind config reads them as `rgb(var(--x))`).
 *
 * Build-time tool, like `materialTheme.ts`: `m3Roles.test.ts` writes the result
 * into the marked region of globals.css when run with `UPDATE_M3_ROLES=1`
 * (`npm run tokens:m3`) and fails if the region ever disagrees with it.
 *
 * What it does NOT touch: `--quality-*`, `--success/warning/danger/info` and the
 * Okabe–Ito class palette. They answer to colour-blindness and to monochrome
 * print, not to brand, and never move with the route.
 */

import { Hct, SchemeContent, argbFromHex, hexFromArgb } from "@material/material-color-utilities";

/** kebab-case role name -> `SchemeContent` getter. */
const ROLES = {
  primary: "primary",
  "on-primary": "onPrimary",
  "primary-container": "primaryContainer",
  "on-primary-container": "onPrimaryContainer",
  secondary: "secondary",
  "on-secondary": "onSecondary",
  "secondary-container": "secondaryContainer",
  "on-secondary-container": "onSecondaryContainer",
  tertiary: "tertiary",
  "on-tertiary": "onTertiary",
  "tertiary-container": "tertiaryContainer",
  "on-tertiary-container": "onTertiaryContainer",
  error: "error",
  "on-error": "onError",
  "error-container": "errorContainer",
  "on-error-container": "onErrorContainer",
  surface: "surface",
  "on-surface": "onSurface",
  "surface-variant": "surfaceVariant",
  "on-surface-variant": "onSurfaceVariant",
  "surface-container-lowest": "surfaceContainerLowest",
  "surface-container-low": "surfaceContainerLow",
  "surface-container": "surfaceContainer",
  "surface-container-high": "surfaceContainerHigh",
  "surface-container-highest": "surfaceContainerHighest",
  outline: "outline",
  "outline-variant": "outlineVariant",
  "inverse-surface": "inverseSurface",
  "inverse-on-surface": "inverseOnSurface",
  "inverse-primary": "inversePrimary",
  "surface-tint": "surfaceTint",
  scrim: "scrim",
  shadow: "shadow",
} as const;

export type M3Role = keyof typeof ROLES;
export const M3_ROLES = Object.keys(ROLES) as M3Role[];

/** Text/icon pairs: the second role is drawn on the first and must reach 4.5:1 (D-34). */
export const M3_TEXT_PAIRS: ReadonlyArray<readonly [M3Role, M3Role]> = [
  ["primary", "on-primary"],
  ["primary-container", "on-primary-container"],
  ["secondary", "on-secondary"],
  ["secondary-container", "on-secondary-container"],
  ["tertiary", "on-tertiary"],
  ["tertiary-container", "on-tertiary-container"],
  ["error", "on-error"],
  ["error-container", "on-error-container"],
  ["surface", "on-surface"],
  ["surface", "on-surface-variant"],
  ["surface-container-highest", "on-surface-variant"],
  ["inverse-surface", "inverse-on-surface"],
];

export function cssName(role: M3Role): string {
  return `--m3-${role}`;
}

function triple(hex: string): string {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
}

/** The roles of one route and theme, as `--m3-*: "R G B"`. */
export function buildRouteRoles(seedHex: string, isDark: boolean): Record<string, string> {
  const scheme = new SchemeContent(Hct.fromInt(argbFromHex(seedHex)), isDark, 0, "2025");
  const out: Record<string, string> = {};
  for (const role of M3_ROLES) {
    out[cssName(role)] = triple(hexFromArgb(scheme[ROLES[role]]));
  }
  return out;
}

export const M3_REGION_BEGIN = "/* m3-roles:begin (generated by lib/design/m3Roles.test.ts, npm run tokens:m3; do not edit) */";
export const M3_REGION_END = "/* m3-roles:end */";

/** `--accent: R G B;` of the first block that opens with `selector {`, as a hex seed. */
function accentSeed(css: string, selector: string): string {
  const open = css.indexOf(`\n${selector} {`);
  if (open < 0) throw new Error(`m3Roles: no block for ${selector}`);
  const body = css.slice(open, css.indexOf("\n}", open));
  const m = /--accent:\s*(\d+) (\d+) (\d+);/.exec(body);
  if (!m) throw new Error(`m3Roles: no --accent in ${selector}`);
  return `#${[m[1], m[2], m[3]].map((v) => Number(v).toString(16).padStart(2, "0")).join("")}`;
}

function block(selector: string, tokens: Record<string, string>): string {
  const lines = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

/**
 * The text between the markers: one light and one dark block for the default
 * blue and for each `[data-section]`. Dark blocks use the compound selector
 * (`[data-theme="dark"][data-section="x"]`), never a descendant combinator —
 * the same reason the hand-written route blocks do.
 */
export function renderM3Region(css: string, sections: readonly string[]): string {
  const parts: string[] = [M3_REGION_BEGIN];
  const light: string[] = [];
  const dark: string[] = [];
  const targets: Array<[string, string, string]> = [
    [":root", "[data-theme=\"dark\"]", accentSeed(css, ":root,\n[data-theme=\"light\"]")],
    ...sections.map((s): [string, string, string] => [
      `[data-section="${s}"]`,
      `[data-theme="dark"][data-section="${s}"]`,
      accentSeed(css, `[data-section="${s}"]`),
    ]),
  ];
  for (const [lightSel, darkSel, seed] of targets) {
    light.push(block(lightSel, buildRouteRoles(seed, false)));
    dark.push(block(darkSel, buildRouteRoles(seed, true)));
  }
  parts.push(...light, ...dark, M3_REGION_END);
  return parts.join("\n");
}
