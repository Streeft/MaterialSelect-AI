"""Which demo processes plausibly make, join and finish each demo material (D-192).

The link table used to be filled **by class only** (``DEFAULT_CLASS_PROCESS_MAP``
and the ``b7d219fa82de`` migration): every ceramic got pressing and sintering —
glass, granite and gypsum included — and every composite got compression
moulding, concrete and timber included. Five classes are too coarse for that
question; the subclass is where the answer lives.

Resolution, in order, all pure (no database):

1. **Base list by (class, subclass)** — ``SUBCLASS_PROCESSES``. A subclass not in
   the table falls back to ``CLASS_FALLBACK`` for its class.
2. **Name rules** — ``NAME_RULES``. A subclass that mixes routes (cast and
   wrought copper alloys, stainless steels inside the generic "Aços", PTFE among
   thermoplastics, sapphire among technical ceramics) is refined by a pattern on
   the material's name: add the routes it has, drop the ones it cannot have.
3. **Restrictions** — ``RESTRICTIONS``. A process that only some members of a
   subclass admit (rotational moulding among thermoplastics, sand casting among
   magnesium alloys) stays only where the name matches.

The table is demonstration data: plausible by order of magnitude and by the
common vocabulary of the method, never a statement that a real supplier makes
a real grade this way. ``test_demo_process_compat.py`` holds the black list of
combinations that must never come out (glass × sintering, concrete × compression
moulding, metal foam × forging …).
"""

