_RESTRICTION_REGEX = {
    key: re.compile(pattern, re.IGNORECASE) for key, pattern in RESTRICTIONS.items()
}


def _restricted_out(class_slug: str, subclass: str | None, name: str, slug: str) -> bool:
    for key in ((class_slug, subclass, slug), (class_slug, None, slug)):
        regex = _RESTRICTION_REGEX.get(key)
        if regex is not None and not regex.search(name):
            return True
    return False


def compatible_process_slugs(class_slug: str, subclass: str | None, name: str) -> list[str]:
    """The demo processes plausible for one material, in a stable order.

    Pure and deterministic: same class, subclass and name, same answer. Returns
    an empty list for a class nobody mapped, never a guess.
    """
    base = SUBCLASS_PROCESSES.get((class_slug, subclass))
    if base is None:
        base = CLASS_FALLBACK.get(class_slug, [])
    chosen: list[str] = list(dict.fromkeys(base))
    for rule in NAME_RULES:
        if rule.class_slug != class_slug or not rule.regex.search(name):
            continue
        if rule.replace:
            chosen = []
        chosen = [slug for slug in chosen if slug not in rule.remove]
        chosen.extend(slug for slug in rule.add if slug not in chosen)
    return [slug for slug in chosen if not _restricted_out(class_slug, subclass, name, slug)]
