def _envelope(slug: str, bounds: tuple[float, float], unit: str) -> dict:
    low, high = bounds
    return {"slug": slug, "kind": "envelope", "min": float(low), "max": float(high), "unit": unit}


def _scalar(slug: str, value: float, unit: str = "dimensionless") -> dict:
    return {"slug": slug, "kind": "scalar", "value": float(value), "unit": unit}


def _selection_values(
    characteristic: str,
    shapes: list[str],
    mass: tuple[float, float],
    section: tuple[float, float],
    batch: float,
) -> list[dict]:
    return [
        _envelope("faixa-massa", mass, "kg"),
        _envelope("espessura-secao", section, "mm"),
        _scalar("lote-economico", batch),
        {"slug": "forma", "kind": "labels", "labels": list(shapes)},
        {"slug": "caracteristica-processo", "kind": "labels", "labels": [characteristic]},
    ]


def _build() -> tuple[list[dict], dict[str, list[dict]]]:
    processes: list[dict] = []
    values: dict[str, list[dict]] = {}
    for row in _SHAPING:
        slug, name, cls, desc, char, shapes, mass, section, batch = row[:9]
        tooling, rate, capital, hourly, scrap, energy = row[9:]
        processes.append({"name": name, "slug": slug, "class_slug": cls, "description": desc})
        values[slug] = [
            *_selection_values(char, shapes, mass, section, batch),
            _scalar("custo-ferramental", tooling),
            _scalar("taxa-producao", rate, "1/hour"),
            _scalar("custo-capital", capital),
            _scalar("custo-hora-operacao", hourly, "1/hour"),
            _scalar("fracao-refugo", scrap),
            _scalar("energia-processo", energy, "MJ/kg"),
            _scalar("co2-processo", round(energy * CO2_PER_MJ, 3)),
        ]
    for rows, char in ((_JOINING, JOINING), (_SURFACE, SURFACE)):
        for slug, name, cls, desc, shapes, mass, section, batch in rows:
            processes.append({"name": name, "slug": slug, "class_slug": cls, "description": desc})
            values[slug] = _selection_values(char, shapes, mass, section, batch)
    return processes, values


