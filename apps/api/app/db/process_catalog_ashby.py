"""The demo process catalogue across Ashby's whole range (D-192).

The 13 processes of P0-2/P0-4 stay exactly as ``app.db.seed`` declares them —
several of their gaps are deliberate test fixtures (``pintura`` with a mass row
that says nobody wrote it, ``retificacao`` without tooling cost). This module
adds the rest of the range the method works with: casting, deformation, powder,
polymer moulding, composite forming, glass, additive manufacturing, machining
(conventional and not), construction and natural materials, joining and
surface treatment.

⚠️  Demonstration data, like every number in the 13 originals. The process
*names* are the common vocabulary of manufacturing engineering; the attribute
values are **order-of-magnitude estimates** written for this catalogue in the
same scale as the originals (unspecified currency), never copied from a
commercial database. They land as ``DataQuality.ESTIMADO`` under the demo
source and the processes are ``is_demo=True``.

Which attributes each process carries follows the rule the originals set
(``test_only_shaping_processes_carry_economics``):

* **Shaping** (everything under *Conformação*, machining included) carries all
  twelve: the five of exercise 11, the five economic ones the Part Cost
  Estimator reads, and the two the Eco Audit reads. Process CO₂ is derived from
  process energy with the factor the seven original shaping rows imply
  (≈0,073 kg CO₂ per MJ), so the two never disagree.
* **Joining** and **surface treatment** carry only the five of exercise 11. A
  part-cost estimate prices *making* the part; a weld or a coat happens to a
  part that already exists, so their economics stay absent on purpose.

Rules tested in ``test_process_catalog_ashby.py``: unique slugs, every class
known, every label in its attribute's closed vocabulary, every envelope with
``min < max``, every scalar positive, scrap fraction in [0, 1).
"""

