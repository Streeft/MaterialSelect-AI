"""Bands of the extended catalogue for the demo materials (D-188): data only.

Every number here is an **order of magnitude by family**, written from the open
literature that teaches materials selection (textbook tables, open handbooks,
standards' typical values) — never from the commercial bases the project
refuses (MatWeb, Total Materia, ASM, MMPDS, CAMPUS). They feed fictitious demo
values only: ``app.db.seed_demo_extended_props`` picks a point inside each band
by a stable hash, derives what physics ties together (G from E and ν, Gc from
K and E, diffusivity from k, ρ and cp…), and writes the result on demo
materials. Nothing here is ever written on a real record.

Shape of a profile (reading units; ``None`` = "não se aplica", written as a
declared absence with a note, never as zero):

* basis — ``rho`` kg/m³, ``E`` GPa, ``nu``, ``su``/``sy`` MPa, ``k`` W/(m·K),
  ``cp`` J/(kg·K), ``a`` 10⁻⁶/K, ``cm`` cost per kg. Used only when the
  material's own core value is absent or implausible (the 70 RNG materials of
  ``seed_extended``); the 593 lots of D-185 always use their own values.
* ``SUB`` MPa: the family's tensile-strength band, which places a material
  inside its toughness bands (stronger → less ductile, less tough).
* bands ``(low, high)`` per quantity, keys listed in ``KEYS`` below.
* ``DUR``: nine ordinal ranks (0 = Muito pobre … 4 = Excelente) in the order of
  ``DURABILITY_SLUGS``; ``INFL``/``TRANS``/``BIO`` ranks.
"""

