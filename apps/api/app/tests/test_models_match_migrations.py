"""The models and the migrations describe the same schema (D-178).

The shared test database is built by ``create_all`` from the models and never
by the migrations, so a model can drift from what Alembic actually created and
no other test notices: the next ``revision --autogenerate`` would then drag
unrelated operations into an unrelated migration. ``alembic check`` after
``upgrade head`` on a scratch SQLite is the guard.
"""

from __future__ import annotations

import logging
from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic.config import Config

from alembic import command
from app.config import settings

API_ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture(autouse=True)
def _keep_logging() -> Iterator[None]:
    # alembic/env.py runs fileConfig, which disables every existing logger.
    loggers = [logging.getLogger(name) for name in list(logging.root.manager.loggerDict)]
    state = [(lg, lg.disabled, lg.level) for lg in loggers]
    root_level = logging.root.level
    root_handlers = list(logging.root.handlers)
    yield
    for logger, disabled, level in state:
        logger.disabled = disabled
        logger.setLevel(level)
    logging.root.setLevel(root_level)
    logging.root.handlers[:] = root_handlers


def test_alembic_check_finds_no_drift_after_upgrade_head(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    url = f"sqlite:///{tmp_path / 'check.db'}"
    # env.py reads the URL from the app settings on every run.
    monkeypatch.setattr(settings, "database_url", url)
    config = Config(str(API_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(API_ROOT / "alembic"))
    config.set_main_option("sqlalchemy.url", url)
    command.upgrade(config, "head")
    # Raises AutogenerateDiffsDetected listing every drifting operation.
    command.check(config)
