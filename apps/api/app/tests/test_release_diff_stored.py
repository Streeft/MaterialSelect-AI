"""TM7-d (D-123): the stored release diff is the live diff, and never outlives its rows.

Everything here runs on a fictitious catalogue generated by
``scripts/bench_release_diff.py`` in a private in-memory database: no real
data, and the counts of SQL statements — not seconds — are what is pinned, so
the CI machine's speed cannot make a test flaky.
"""

from __future__ import annotations

import math
from collections.abc import Generator

import pytest
from sqlalchemy import create_engine, event, select, text
from sqlalchemy.orm import Session
from sqlalchemy.pool import StaticPool

from app.calculations.units import to_canonical
from app.db.base import Base, json_serializer
from app.domain.release_diff import ValueSnapshot, compare_values, diff_releases
from app.domain.release_diff_store import NotStorable, dump_diffs, load_diffs
from app.exporters.spreadsheet import to_csv as render_csv
from app.models import CatalogReleaseDiff, Material, MaterialPropertyValue
from app.models.enums import DataQuality
from app.services.catalog_release_service import CatalogReleaseService
from app.tests.synthetic_catalog import build


def _session(records: int, properties: int = 6) -> Session:
    engine = create_engine("sqlite://", poolclass=StaticPool, json_serializer=json_serializer)
    Base.metadata.create_all(engine)
    db = Session(engine)
    build(db, records=records, properties=properties, points=4)
    db.commit()
    return db


@pytest.fixture()
def db() -> Generator[Session, None, None]:
    session = _session(30)
    try:
        yield session
    finally:
        session.close()


def _everything(service: CatalogReleaseService) -> tuple:
    page = service.diff("bench-r1", "bench-r2", page_size=200).model_dump(mode="json")
    one = service.record("bench-r1", "bench-r2", "MaterialUniverse", "m-0").model_dump(mode="json")
    changed = service.diff("bench-r1", "bench-r2", tipo="alterado").model_dump(mode="json")
    report = render_csv(service.diff_report("bench-r1", "bench-r2"))
    return page, one, changed, report


def _stored_rows(db: Session) -> int:
    return len(db.execute(select(CatalogReleaseDiff.id)).all())


def test_the_stored_diff_answers_exactly_what_the_rows_answer(db: Session) -> None:
    service = CatalogReleaseService(db)
    live = _everything(service)
    assert service.materialize_previous("bench-r2") == 30
    db.commit()
    assert service._stored(1, 2) is not None  # the next answers come from the store
    assert _everything(service) == live
    assert live[0]["counts"] and live[2]["total"] == 30
    assert any(item["status"] == "alterado" for item in live[0]["items"])


def test_absence_round_trips_as_absence_never_zero() -> None:
    db = _session(10)
    service = CatalogReleaseService(db)
    diffs, _ = service._live(1, 2)
    again = load_diffs(dump_diffs(diffs))
    assert again == [
        type(d)(d.external_table, d.external_record_id, d.status, *_headers(d), d.changes)
        for d in diffs
    ]
    missing = ValueSnapshot(is_missing=True)
    (stored,) = load_diffs(dump_diffs([_one_change(missing)]))
    assert stored.changes[0].before_value == missing
    assert stored.changes[0].before_value.value_scalar is None


def _headers(diff):
    from dataclasses import replace

    return tuple(
        None if side is None else replace(side, values={}, composition={}, curves={})
        for side in (diff.base, diff.target)
    )


def _one_change(before: ValueSnapshot):
    from app.domain.release_diff import ChangeKind, FieldChange, RecordDiff, RecordStatus

    return RecordDiff(
        "T",
        "1",
        RecordStatus.CHANGED,
        None,
        None,
        (FieldChange("propriedade:x", "X", ChangeKind.PRESENCE, before_value=before),),
    )


def test_a_non_finite_number_is_not_stored() -> None:
    with pytest.raises(NotStorable):
        dump_diffs([_one_change(ValueSnapshot(is_missing=False, value_scalar=math.inf))])


def test_writing_a_catalogue_value_drops_every_stored_diff(db: Session) -> None:
    service = CatalogReleaseService(db)
    service.materialize_previous("bench-r2")
    db.commit()
    value = (
        db.execute(select(MaterialPropertyValue).where(MaterialPropertyValue.material_id == 31))
        .scalars()
        .first()
    )
    assert value is not None
    value.value_min = 123456.0
    db.flush()
    assert _stored_rows(db) == 0
    db.rollback()  # a rollback brings the stored diff back with the row
    assert _stored_rows(db) == 1


def test_writing_a_persons_own_record_keeps_the_stored_diff(db: Session) -> None:
    service = CatalogReleaseService(db)
    service.materialize_previous("bench-r2")
    db.commit()
    own = Material(name="Liga própria", class_id=1, owner_id=None, is_demo=True)
    db.add(own)
    db.flush()
    db.add(
        MaterialPropertyValue(
            material_id=own.id,
            property_id=1,
            is_missing=True,
            source_id=1,
            data_quality=DataQuality.IMPORTADO,
        )
    )
    db.flush()
    assert _stored_rows(db) == 1


def test_a_bulk_statement_on_a_catalogue_table_drops_them(db: Session) -> None:
    from sqlalchemy import update

    CatalogReleaseService(db).materialize_previous("bench-r2")
    db.commit()
    db.execute(update(Material).where(Material.id == 1).values(description="outra"))
    assert _stored_rows(db) == 0


def test_a_row_deleted_by_hand_fails_the_fingerprint(db: Session) -> None:
    service = CatalogReleaseService(db)
    live = _everything(service)
    service.materialize_previous("bench-r2")
    db.commit()
    # Raw SQL, invisible to the session listeners: only the fingerprint sees it.
    db.execute(
        text(
            "DELETE FROM material_curve_point WHERE id = (SELECT MAX(id) FROM material_curve_point)"
        )
    )
    assert _stored_rows(db) == 1
    assert service._stored(1, 2) is None
    assert _everything(service) != live  # served from the rows, with the change


def test_another_format_version_is_never_served(db: Session) -> None:
    service = CatalogReleaseService(db)
    service.materialize_previous("bench-r2")
    row = db.execute(select(CatalogReleaseDiff)).scalar_one()
    row.format_version = 999
    db.flush()
    assert service._stored(1, 2) is None


def _statements(db: Session, records: int) -> int:
    seen: list[str] = []
    engine = db.get_bind()
    listener = lambda *args: seen.append(args[2])  # noqa: E731
    event.listen(engine, "before_cursor_execute", listener)
    try:
        CatalogReleaseService(db).diff("bench-r1", "bench-r2")
    finally:
        event.remove(engine, "before_cursor_execute", listener)
    return len(seen)


def test_the_number_of_statements_does_not_grow_with_the_catalogue() -> None:
    small, large = _session(5), _session(60)
    assert _statements(small, 5) == _statements(large, 60)
    for db in (small, large):
        CatalogReleaseService(db).materialize_previous("bench-r2")
        db.commit()
    assert _statements(small, 5) == _statements(large, 60)


def test_identical_values_skip_the_conversion_and_agree_with_it() -> None:
    a = ValueSnapshot(
        is_missing=False, value_min=1.0, value_max=2.0, original_unit="MPa", canonical_unit="Pa"
    )
    assert compare_values(a, ValueSnapshot(**a.__dict__), "Pa") is None
    nan = ValueSnapshot(is_missing=False, value_scalar=1.0, normalized_value=float("nan"))
    # A NaN goes the long way and is never "unchanged" by accident.
    assert compare_values(nan, ValueSnapshot(**nan.__dict__), "Pa") is not None


def test_the_unit_parse_cache_changes_no_number() -> None:
    from app.calculations.units import ureg

    for value, origin, target in (
        (1.5, "MPa", "Pa"),
        (20.0, "degC", "K"),
        (3.0, "g/cm**3", "kg/m**3"),
    ):
        expected = float(ureg.Quantity(value, origin).to(target).magnitude)
        assert to_canonical(value, origin, target)[0] == expected


def test_live_diff_still_matches_the_domain() -> None:
    db = _session(8)
    service = CatalogReleaseService(db)
    diffs, keys = service._live(1, 2)
    assert diffs == diff_releases(
        service.repo.snapshots(1), service.repo.snapshots(2), service._properties(keys)
    )
